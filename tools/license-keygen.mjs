#!/usr/bin/env node
// Create the vendor signing keypair used by licence activation.
//   node tools/license-keygen.mjs [--force]
// The private key is written to vendor/license-private-key.pem (git-ignored).
// Back it up somewhere safe. If you lose it you must create a new keypair and
// reissue every licence, because the app only trusts the public key in
// lib/license-public.mjs.
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { generateKeyPairSync } from "node:crypto";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const force = process.argv.includes("--force");
const privatePath = join(root, "vendor", "license-private-key.pem");
const publicPath = join(root, "lib", "license-public.mjs");

if (existsSync(privatePath) && !force) {
  console.error(`A private key already exists at ${privatePath}`);
  console.error("Refusing to overwrite it. Use --force only if you intend to invalidate every existing licence.");
  process.exit(1);
}

const { publicKey, privateKey } = generateKeyPairSync("ed25519");
const publicKeyPem = publicKey.export({ type: "spki", format: "pem" }).toString();
const privateKeyPem = privateKey.export({ type: "pkcs8", format: "pem" }).toString();

mkdirSync(dirname(privatePath), { recursive: true });
writeFileSync(privatePath, privateKeyPem, { mode: 0o600 });
writeFileSync(publicPath, `// Generated by tools/license-keygen.mjs. Safe to commit: this is the PUBLIC key.\nexport const PUBLIC_KEY_PEM = ${JSON.stringify(publicKeyPem)};\n`);
console.log("Private key:", privatePath);
console.log("Public key: ", publicPath);
console.log("\nKeep vendor/license-private-key.pem offline and backed up. Never commit it.");
